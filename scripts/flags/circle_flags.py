"""Converts round flags from circle-flags into Android vector drawables.

    python scripts/flags/circle_flags.py overlay/src/main/res/drawable [--source <directory of SVG files>]

Without --source the SVG files are downloaded from the circle-flags repository at COMMIT. Each flag becomes
`flag_<country>.xml`. The flags are drawn on a 512 x 512 square and masked by a circle; the drawable clips them to the
same circle. Only the elements the flags use are converted (path, circle, rect); anything else stops the script, so a
new flag that needs more is noticed. circle-flags is MIT licensed (see NOTICE).
"""
import argparse
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree

COMMIT = "379588b5da95482d6bbf10bd45644a35b0609ea6"
URL = "https://raw.githubusercontent.com/HatScripts/circle-flags/{commit}/flags/{country}.svg"

# The countries LanguageSupport.flagCountries names, in the order of the languages.
COUNTRIES = [
    "jp", "us", "gb", "cn", "kr", "es", "fr", "de", "it", "br", "pt", "pl", "tr", "lv", "nl", "cz", "id", "my", "ph", "vn", "ru",
    "hr", "rs", "ua", "by", "gr", "in", "bd", "ge", "am", "th", "kh", "sa", "ir", "il", "kz", "kg",
]

SVG = "{http://www.w3.org/2000/svg}"
SIZE = 512
CIRCLE_MASK = {"cx": "256", "cy": "256", "r": "256"}

HEADER = (
    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
    "<!-- Generated by scripts/flags/circle_flags.py from circle-flags {commit} ({country}.svg), MIT license. -->\n"
)


class UnsupportedSvg(Exception):
    pass


def number(value):
    """A number as short as it can be written: 256 rather than 256.0."""
    text = f"{float(value):.3f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def color(value):
    """#rgb as #rrggbb; Android reads both, the long form keeps the files uniform."""
    if not re.fullmatch(r"#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6}", value or ""):
        raise UnsupportedSvg(f"fill {value!r}")
    if len(value) == 4:
        value = "#" + "".join(c * 2 for c in value[1:])
    return value.lower()


def circle_path(cx, cy, r):
    cx, cy, r = float(cx), float(cy), float(r)
    return (
        f"M{number(cx - r)},{number(cy)}"
        f"a{number(r)},{number(r)} 0 1,0 {number(2 * r)},0"
        f"a{number(r)},{number(r)} 0 1,0 {number(-2 * r)},0z"
    )


def rect_path(x, y, width, height, rx, ry):
    x, y, w, h = float(x), float(y), float(width), float(height)
    rx = float(rx if rx is not None else ry if ry is not None else 0)
    ry = float(ry if ry is not None else rx)
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    if rx == 0 or ry == 0:
        return f"M{number(x)},{number(y)}h{number(w)}v{number(h)}h{number(-w)}z"
    return (
        f"M{number(x + rx)},{number(y)}"
        f"h{number(w - 2 * rx)}a{number(rx)},{number(ry)} 0 0,1 {number(rx)},{number(ry)}"
        f"v{number(h - 2 * ry)}a{number(rx)},{number(ry)} 0 0,1 {number(-rx)},{number(ry)}"
        f"h{number(-(w - 2 * rx))}a{number(rx)},{number(ry)} 0 0,1 {number(-rx)},{number(-ry)}"
        f"v{number(-(h - 2 * ry))}a{number(rx)},{number(ry)} 0 0,1 {number(rx)},{number(-ry)}z"
    )


def shapes(svg_text):
    """The (path data, fill) pairs of a circle-flags SVG, in drawing order."""
    root = ElementTree.fromstring(svg_text)
    if root.get("viewBox") != f"0 0 {SIZE} {SIZE}":
        raise UnsupportedSvg(f"viewBox {root.get('viewBox')!r}")
    children = list(root)
    if len(children) != 2 or children[0].tag != SVG + "mask" or children[1].tag != SVG + "g":
        raise UnsupportedSvg("expected a mask and a group")
    mask = list(children[0])
    if len(mask) != 1 or mask[0].tag != SVG + "circle" or any(mask[0].get(k) != v for k, v in CIRCLE_MASK.items()):
        raise UnsupportedSvg("the mask is not the full circle")
    if children[1].get("mask") != f"url(#{children[0].get('id')})":
        raise UnsupportedSvg("the group is not masked by the circle")
    result = []
    for element in children[1]:
        tag = element.tag.removeprefix(SVG)
        attributes = set(element.attrib)
        if tag == "path" and attributes == {"d", "fill"}:
            data = element.get("d")
        elif tag == "circle" and attributes == {"cx", "cy", "r", "fill"}:
            data = circle_path(element.get("cx"), element.get("cy"), element.get("r"))
        elif tag == "rect" and {"width", "height", "fill"} <= attributes <= {"x", "y", "width", "height", "rx", "ry", "fill"}:
            data = rect_path(
                element.get("x", "0"), element.get("y", "0"), element.get("width"), element.get("height"),
                element.get("rx"), element.get("ry"),
            )
        else:
            raise UnsupportedSvg(f"<{tag}> with {sorted(attributes)}")
        result.append((data, color(element.get("fill"))))
    return result


def vector_drawable(svg_text, country, commit=COMMIT):
    lines = [
        HEADER.format(commit=commit, country=country).rstrip("\n"),
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        f'    android:viewportWidth="{SIZE}"',
        f'    android:viewportHeight="{SIZE}">',
        f'    <clip-path android:pathData="{circle_path(256, 256, 256)}" />',
    ]
    for data, fill in shapes(svg_text):
        lines.append(f'    <path android:fillColor="{fill}" android:pathData="{data}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def read_svg(country, source):
    if source:
        with open(os.path.join(source, f"{country}.svg"), encoding="utf-8") as file:
            return file.read()
    with urllib.request.urlopen(URL.format(commit=COMMIT, country=country), timeout=30) as response:
        return response.read().decode("utf-8")


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out", help="the drawable directory the flags go to")
    parser.add_argument("--source", help="a directory with the SVG files of COMMIT instead of downloading them")
    args = parser.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    for country in COUNTRIES:
        drawable = vector_drawable(read_svg(country, args.source), country)
        with open(os.path.join(args.out, f"flag_{country}.xml"), "w", encoding="utf-8", newline="\n") as file:
            file.write(drawable)
        print(f"flag_{country}.xml: {len(drawable)} bytes")


if __name__ == "__main__":
    main(sys.argv[1:])
